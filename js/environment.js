/* 生成一个图标 SVG（stroke 用 currentColor，颜色由外层 CSS 决定）。
   stroke-width 给到 2：游戏本身是粗线条手绘风，细线在这种深色小方块里会显得发虚。 */
function envIconSvg(name, cls) {
  const p = ENV_ICONS[name] || ENV_CAT_ICONS[name] || ENV_CAT_ICONS.cloud;
  return `<svg class="${cls || 'env-svg'}" viewBox="0 0 24 24" fill="none" stroke="currentColor"
    stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${p}</svg>`;
}

